/**
 * スタンダードデッキ8種（2026-07-26 全部組み直し）。
 *
 * 組み直した理由: 旧デッキは「そのキャラが撃てない札」だらけだった。
 * アクターはスキル1回ごとに交代するので、前に出たキャラが撃てないと1ターン丸損になる。
 * 実測では ビコウ10% / ドッソ23% / パークル13% / アイ30% しか自分のデッキを撃てておらず、
 * 「カードが弱い」ように見えていた原因はここだった（並び順だけで勝率が最大19ポイント動いた）。
 *
 * 今の作り方:
 * 1. まず「全員が撃てる属性」でチームを決める（＝どのキャラが前でも手が止まらない）
 * 2. その属性の札を厚く積み、一番撃てないキャラを助ける札から優先して入れる
 * 3. キャラ札は各2枚（同名回復）、革の鎧2枚は無条件で腐らないので固定
 * 4. シミュレーターの総当たりで検証（engine/src/sim/run.ts）
 *
 * 構成は決定的（ランダム無し）なので、テスト・シミュレーションの再現ができる。
 * 各デッキの「撃てる率」は 60% 前後を下回らないこと。下回ったら組み直しのサイン。
 */
